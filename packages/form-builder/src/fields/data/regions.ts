const countryLabelByValue = new Map(COUNTRIES.map((country) => [country.value, country.label]))
const usStateLabelByValue = new Map(US_STATES.map((state) => [state.value, state.label]))

/** The English name for an ISO country code, or `undefined` when the code is not a known country. */
export const countryLabel = (value: string): string | undefined => countryLabelByValue.get(value)

/** The name for a US state/DC code, or `undefined` when the code is not a known state. */
export const usStateLabel = (value: string): string | undefined => usStateLabelByValue.get(value)

/** Whether `value` is a known ISO country code. */
export const isCountryCode = (value: string): boolean => countryLabelByValue.has(value)

/** Whether `value` is a known US state/DC code. */
export const isUsStateCode = (value: string): boolean => usStateLabelByValue.has(value)

const FIXED_FIELD_OPTIONS: Record<string, { label: string; value: string }[]> = {
	country: COUNTRIES,
	state: US_STATES,
}

/**
 * The fixed option set a built-in field type carries in code (country/state), or `undefined` for
 * every other type. Lets surfaces that key off authored `options` (the condition builder) offer the
 * same choices for these types, which author none.
 */
export const fixedFieldOptions = (
	blockType: string
): { label: string; value: string }[] | undefined => FIXED_FIELD_OPTIONS[blockType]
